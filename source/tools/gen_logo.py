#!/usr/bin/env python3
"""The start screen's picture: ../docs/img/logo-k-wasub.png -> firmware/gen/ksub_logo.h (216 x 216, 16 grey levels, 4 bits a pixel,
two to a byte, the left one in the high nibble). Run from source/:  python3 tools/gen_logo.py   (needs Pillow)"""
from pathlib import Path
from PIL import Image, ImageFilter
N = 216
im = Image.open("../docs/img/logo-k-wasub.png").convert("L")
side = min(im.size)
im = im.crop(((im.width - side) // 2, 0, (im.width - side) // 2 + side, side)).resize((N, N), Image.LANCZOS)
im = im.filter(ImageFilter.UnsharpMask(radius=1.2, percent=90, threshold=2))
px = [min(15, max(0, round(v / 17))) for v in im.getdata()]
out = [px[i] << 4 | px[i + 1] for i in range(0, len(px), 2)]
rows = []
for i in range(0, len(out), 24):
    rows.append("    " + ", ".join(f"0x{b:02X}" for b in out[i:i + 24]) + ",")
Path("firmware/gen/ksub_logo.h").write_text(
    "/* generated by tools/gen_logo.py: the start screen's picture, %d x %d, 4 bits a pixel */\n#define KS_LOGO_N %d\nstatic const uint8_t KS_LOGO[%d] = {\n%s\n};\n"
    % (N, N, N, len(out), "\n".join(rows)))
print(len(out), "bytes")
