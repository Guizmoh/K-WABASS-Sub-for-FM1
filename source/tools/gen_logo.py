#!/usr/bin/env python3
"""The start screen's picture: ../docs/img/logo-k-wasub.png -> firmware/gen/ksub_logo.h (216 x 216, 16 grey levels, 4 bits a pixel,
two to a byte, the left one in the high nibble; the black packed: a 0x00 byte is followed by how many black bytes, 1..255,
the rest as is; each row starts at KS_LOGO_ROW[y]). Run from source/:  python3 tools/gen_logo.py   (needs Pillow)"""
from pathlib import Path
from PIL import Image, ImageFilter
N = 216
im = Image.open("../docs/img/logo-k-wasub.png").convert("L")
side = min(im.size)
im = im.crop(((im.width - side) // 2, 0, (im.width - side) // 2 + side, side)).resize((N, N), Image.LANCZOS)
im = im.filter(ImageFilter.UnsharpMask(radius=1.2, percent=90, threshold=2))
px = [min(15, max(0, round(v / 17))) for v in im.getdata()]
out = [px[i] << 4 | px[i + 1] for i in range(0, len(px), 2)]
pk, starts = [], []
for y in range(N):                       # only the black is packed: runs of 0x00 bytes, row by row
    starts.append(len(pk))
    r, i = out[y * N // 2:(y + 1) * N // 2], 0
    while i < len(r):
        if r[i]:
            pk.append(r[i]); i += 1
        else:
            n = 1
            while i + n < len(r) and not r[i + n] and n < 255: n += 1
            pk += [0, n]; i += n
rows = ["    " + ", ".join(f"0x{b:02X}" for b in pk[i:i + 24]) + "," for i in range(0, len(pk), 24)]
Path("firmware/gen/ksub_logo.h").write_text(
    "/* generated by tools/gen_logo.py: the start screen's picture, %d x %d, 4 bits a pixel, the black packed */\n#define KS_LOGO_N %d\n"
    "static const uint16_t KS_LOGO_ROW[%d] = {%s};\nstatic const uint8_t KS_LOGO[%d] = {\n%s\n};\n"
    % (N, N, N, N, ", ".join(map(str, starts)), len(pk), "\n".join(rows)))
print(len(out), "bytes ->", len(pk) + 2 * N, "packed")
